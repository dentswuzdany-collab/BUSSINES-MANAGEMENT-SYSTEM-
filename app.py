# ==================== NEON POSTGRESQL DATABASE ====================

def get_db():
    """Connect to Neon PostgreSQL using a request-scoped connection."""

    if "db" not in g:

        database_url = os.environ.get("DATABASE_URL")

        if not database_url:
            raise RuntimeError(
                "DATABASE_URL is missing. "
                "Add your Neon PostgreSQL connection string "
                "to the Render environment variables."
            )

        g.db = psycopg.connect(
            database_url,
            row_factory=dict_row,
            connect_timeout=15,
            sslmode="require"
        )

    return g.db


@app.teardown_appcontext
def close_db(error=None):

    db = g.pop("db", None)

    if db is not None:

        if error is not None:
            db.rollback()

        db.close()


def init_db():
    """Create all required tables in Neon PostgreSQL."""

    db = get_db()

    db.execute("""
        CREATE TABLE IF NOT EXISTS stock (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            item TEXT NOT NULL,
            initial_quantity INTEGER NOT NULL DEFAULT 0,
            unit_price NUMERIC(14,2) NOT NULL DEFAULT 0,
            total_amount NUMERIC(16,2) NOT NULL DEFAULT 0,
            remaining_quantity INTEGER NOT NULL DEFAULT 0,
            date_added TEXT NOT NULL,
            low_stock_level INTEGER NOT NULL DEFAULT 5
        )
    """)

    db.execute("""
        CREATE TABLE IF NOT EXISTS admin (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            password_hash TEXT NOT NULL,
            salt TEXT
        )
    """)

    db.execute("""
        CREATE TABLE IF NOT EXISTS sales (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            stock_id BIGINT NOT NULL REFERENCES stock(id),
            item TEXT NOT NULL,
            quantity_sold INTEGER NOT NULL,
            buying_price NUMERIC(14,2) NOT NULL,
            selling_price NUMERIC(14,2) NOT NULL,
            revenue NUMERIC(16,2) NOT NULL,
            cost NUMERIC(16,2) NOT NULL,
            profit_loss NUMERIC(16,2) NOT NULL,
            sale_date TEXT NOT NULL
        )
    """)

    db.execute("""
        CREATE TABLE IF NOT EXISTS deliveries (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            stock_id BIGINT NOT NULL REFERENCES stock(id),
            item TEXT NOT NULL,
            quantity_received INTEGER NOT NULL,
            buying_price NUMERIC(14,2) NOT NULL,
            total_cost NUMERIC(16,2) NOT NULL,
            delivery_date TEXT NOT NULL
        )
    """)

    db.execute("""
        CREATE TABLE IF NOT EXISTS expenses (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            description TEXT NOT NULL,
            amount NUMERIC(16,2) NOT NULL,
            expense_date TEXT NOT NULL
        )
    """)

    # Ensure older Neon installations have the required columns.
    db.execute("""
        ALTER TABLE stock
        ADD COLUMN IF NOT EXISTS low_stock_level
        INTEGER NOT NULL DEFAULT 5
    """)

    db.execute("""
        ALTER TABLE admin
        ADD COLUMN IF NOT EXISTS salt TEXT
    """)

    db.commit()


